package ru.florify.media.domain.model;

/**
 * Статус медиафайла в жизненном цикле.
 */
public enum MediaFileStatus {
    /**
     * Файл загружен, идёт обработка (генерация вариантов, загрузка в MinIO).
     */
    PROCESSING,

    /**
     * Файл успешно обработан, все варианты доступны в MinIO.
     */
    READY,

    /**
     * Файл помечен удалённым (soft delete). Варианты удалены из MinIO.
     */
    DELETED,

    /**
     * Ошибка при обработке (неподдерживаемый формат, сбой MinIO, etc.).
     * Файл остаётся в этом статусе. Для повторной попытки нужно загрузить заново.
     */
    ERROR
}
